### 📌 ক্যাটাগরি ৪: ট্রাবলশুটিং ও আর্কিটেকচারাল সিনারিও

#### প্রশ্ন ১৯: সিনারিও: Client VPC থেকে Model VPC-তে কার্ল করলে 'Connection Timed Out' দিচ্ছে। কীভাবে ট্রাবলশুট করবেন?
